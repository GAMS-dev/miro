#!/bin/bash

# Persist release metadata, prepare artifacts and build the Sphinx documentation.
# Artifact versions/hashes are injected into the generated download page only.
set -euo pipefail

case "$(uname)" in
    Linux ) DATEBIN=date ;;
    Darwin ) DATEBIN=gdate ;;
    *) echo "Currently only Linux/macOS supported." >&2 && exit 1 ;;
esac

DOC_OUTPUT_DIR="${DOC_OUTPUT_DIR:-./doc/_build/html}"
SPHINX_PYTHON="${SPHINX_PYTHON:-./doc/.venv/bin/python}"

require_file() {
    if [[ ! -f "$1" ]]; then
        echo "Required file is missing: $1" >&2
        exit 1
    fi
}

require_output_file() {
    require_file "${DOC_OUTPUT_DIR}/$1"
}

insert_after_marker() {
    local page="$1"
    local marker="$2"
    local content="$3"
    local temporary

    if ! grep -Fq "$marker" "$page"; then
        echo "Expected marker is missing from $page: $marker" >&2
        exit 1
    fi

    temporary=$(mktemp "${page}.XXXXXX")
    sed "\\|${marker}|r ${content}" "$page" > "$temporary"
    mv "$temporary" "$page"
    chmod 644 "$page"
}

html_escape() {
    sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g; s/"/\&quot;/g; s/'"'"'/\&#39;/g' "$1" > "$2"
}

require_file ./.hashes.txt
# .hashes.txt is generated by the release job and contains simple KEY=VALUE
# assignments for the authoritative artifact hashes.
set -a
source ./.hashes.txt
set +a

for hash_name in \
    MIRO_SHA_HASH_WIN \
    MIRO_SHA_HASH_MAC_ARM \
    MIRO_SHA_HASH_MAC_X86 \
    MIRO_SHA_HASH_LINUX \
    MIRO_SHA_HASH_DEB_LINUX \
    MIRO_SHA_HASH_RPM_LINUX
do
    if [[ -z "${!hash_name:-}" ]]; then
        echo "Required release hash is missing: ${hash_name}" >&2
        exit 1
    fi
done

require_file ./src/LICENSE
require_file ./server/LICENSE
require_file ./src/conf/config_schema.json
require_file ./ci-vuln-report.html
require_file "$SPHINX_PYTHON"

./scripts/create_miro_lib.sh > /dev/null

MIRO_VERSION_FULL=$(grep -m 1 -e "^MIROVersion" src/app.R | cut -f3 -d" " | xargs)
MIRO_VERSION_MAJOR=$(echo "$MIRO_VERSION_FULL" | cut -f1 -d".")
MIRO_VERSION_MINOR=$(echo "$MIRO_VERSION_FULL" | cut -f2 -d".")
MIRO_VERSION_SHORT="${MIRO_VERSION_MAJOR}.${MIRO_VERSION_MINOR}"
MIRO_RELEASE_DATE=$(grep -m 1 -e 'MIRORDate' src/app.R | cut -f2 -d'"' | xargs -0 "$DATEBIN" +%Y-%m-%d -d )

# Freeze the release date and advertised version in the sources. push_docs.sh
# commits these files, so future releases cannot re-date historical entries.
python3 ./scripts/update_docs_release.py --version "$MIRO_VERSION_FULL" --date "$MIRO_RELEASE_DATE"

pushd server > /dev/null
    python3 miro_server.py release -f
popd > /dev/null

require_file ./server/miro_server.zip
require_file ./doc/GAMS-MIRO-Demo-Apps.zip
require_file ./doc/GAMS-MIRO-Demo-Apps-GAMSPy.zip

rm -rf "$DOC_OUTPUT_DIR"
"$SPHINX_PYTHON" -m sphinx \
    -b html \
    -n \
    -W \
    --keep-going \
    ./doc/source \
    "$DOC_OUTPUT_DIR"

for page in index.html download.html license.html license-server.html schema.html security_ci_report.html release.html; do
    require_output_file "$page"
done

download_page="${DOC_OUTPUT_DIR}/download.html"
download_temporary=$(mktemp "${download_page}.XXXXXX")
sed \
    -e "s|__VERSION_FULL__|${MIRO_VERSION_FULL}|g" \
    -e "s|__VERSION__|${MIRO_VERSION_SHORT}|g" \
    -e "s|__SHA_HASH_WIN__|${MIRO_SHA_HASH_WIN}|g" \
    -e "s|__SHA_HASH_MAC_ARM__|${MIRO_SHA_HASH_MAC_ARM}|g" \
    -e "s|__SHA_HASH_MAC_X86__|${MIRO_SHA_HASH_MAC_X86}|g" \
    -e "s|__SHA_HASH_DEB_LINUX__|${MIRO_SHA_HASH_DEB_LINUX}|g" \
    -e "s|__SHA_HASH_RPM_LINUX__|${MIRO_SHA_HASH_RPM_LINUX}|g" \
    -e "s|__SHA_HASH_LINUX__|${MIRO_SHA_HASH_LINUX}|g" \
    "$download_page" > "$download_temporary"
mv "$download_temporary" "$download_page"
chmod 644 "$download_page"

license_escaped=$(mktemp)
server_license_escaped=$(mktemp)
schema_escaped=$(mktemp)
trap 'rm -f "$license_escaped" "$server_license_escaped" "$schema_escaped"' EXIT
html_escape ./src/LICENSE "$license_escaped"
html_escape ./server/LICENSE "$server_license_escaped"
html_escape ./src/conf/config_schema.json "$schema_escaped"
insert_after_marker "${DOC_OUTPUT_DIR}/license.html" '<pre id="miro-license">' "$license_escaped"
insert_after_marker "${DOC_OUTPUT_DIR}/license-server.html" '<pre id="miro-license">' "$server_license_escaped"
insert_after_marker "${DOC_OUTPUT_DIR}/schema.html" '<pre><code class="language-json config-schema-container">' "$schema_escaped"

security_page="${DOC_OUTPUT_DIR}/security_ci_report.html"
if ! grep -Fq '<div id="ci-vuln-report"></div>' "$security_page"; then
    echo "Expected CI vulnerability report marker is missing from $security_page" >&2
    exit 1
fi
security_temporary=$(mktemp "${security_page}.XXXXXX")
awk '
    /<div id="ci-vuln-report"><\/div>/ {
        print "<div id=\"ci-vuln-report\">"
        while ((getline line < "./ci-vuln-report.html") > 0) {
            print line
        }
        close("./ci-vuln-report.html")
        print "</div>"
        next
    }
    { print }
' "$security_page" > "$security_temporary"
mv "$security_temporary" "$security_page"
chmod 644 "$security_page"

release_page="${DOC_OUTPUT_DIR}/release.html"
index_page="${DOC_OUTPUT_DIR}/index.html"

mv ./server/miro_server.zip "${DOC_OUTPUT_DIR}/GAMS-MIRO-Server-${MIRO_VERSION_FULL}.zip"
mv ./doc/GAMS-MIRO-Demo-Apps.zip "${DOC_OUTPUT_DIR}/GAMS-MIRO-Demo-Apps.zip"
mv ./doc/GAMS-MIRO-Demo-Apps-GAMSPy.zip "${DOC_OUTPUT_DIR}/GAMS-MIRO-Demo-Apps-GAMSPy.zip"
echo "$MIRO_VERSION_FULL" | sed 's/\./,/g' > "${DOC_OUTPUT_DIR}/latest.ver"

for artifact in \
    "GAMS-MIRO-Server-${MIRO_VERSION_FULL}.zip" \
    GAMS-MIRO-Demo-Apps.zip \
    GAMS-MIRO-Demo-Apps-GAMSPy.zip \
    latest.ver \
    miro_server_api.json \
    assets/images/logo.svg \
    _static/redoc.standalone.js
do
    require_output_file "$artifact"
done

for page in "$download_page" "$index_page" "$release_page"; do
    if grep -Eq '__VERSION(_FULL)?__|__SHA_HASH_[A-Z_]+__|xxxx-xx-xx' "$page"; then
        echo "Unresolved release placeholders remain in $page" >&2
        exit 1
    fi
done

if ! grep -Fq ">Get GAMS MIRO ${MIRO_VERSION_FULL}</span>" "$index_page"; then
    echo "Current version ${MIRO_VERSION_FULL} is not advertised in $index_page" >&2
    exit 1
fi

# Validate the current major/minor entry or its newest nested patch release.
python3 ./scripts/update_docs_release.py \
    --html-file "$release_page" \
    --version "$MIRO_VERSION_FULL" \
    --date "$MIRO_RELEASE_DATE"
